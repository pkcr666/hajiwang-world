// 遗物带来的六维汇总（幸运影响幸运掉落判定）
export function sumRelicSixStats(relicIds: string[]): ExtraStats {
  const out: ExtraStats = { str: 0, int: 0, agi: 0, luk: 0, cha: 0, wil: 0 };
  for (const id of relicIds) {
    const r = RELIC_MAP[id];
    if (r?.effect.kind !== 'sixStats') continue;
    for (const k of Object.keys(out) as (keyof ExtraStats)[]) {
      out[k] += r.effect.bonus[k] ?? 0;
    }
  }
  return out;
}

